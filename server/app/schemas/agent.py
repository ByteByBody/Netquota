"""Agent-facing schemas: enrollment, heartbeat, usage reports."""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from ..models.enums import MeasurementQuality, MeasurementScope, Platform

SCHEMA_VERSION = 1


class EnrollIn(BaseModel):
    enrollment_code: str = Field(min_length=4, max_length=256)
    name: str = Field(min_length=1, max_length=200)
    platform: str = Field(max_length=32)
    agent_version: str | None = Field(default=None, max_length=64)
    measurement_scope: str = Field(default=MeasurementScope.UNKNOWN, max_length=32)
    measurement_quality: str = Field(default=MeasurementQuality.UNKNOWN, max_length=32)
    capabilities: dict = Field(default_factory=dict)
    # Stable per-installation id generated by the agent (survives reinstalls).
    installation_id: str | None = Field(default=None, max_length=128)

    @field_validator("platform")
    @classmethod
    def _platform(cls, v: str) -> str:
        if v not in Platform.ALL:
            raise ValueError(f"unsupported platform: {v}")
        return v

    @field_validator("measurement_scope")
    @classmethod
    def _scope(cls, v: str) -> str:
        if v not in MeasurementScope.ALL:
            raise ValueError(f"unsupported measurement_scope: {v}")
        return v

    @field_validator("measurement_quality")
    @classmethod
    def _quality(cls, v: str) -> str:
        if v not in MeasurementQuality.ALL:
            raise ValueError(f"unsupported measurement_quality: {v}")
        return v


class EnrollOut(BaseModel):
    device_id: str
    credential: str
    heartbeat_interval_seconds: int
    reporting_interval_seconds: int
    server_time: datetime


class HeartbeatIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    schema_version: int = SCHEMA_VERSION
    agent_version: str | None = Field(default=None, max_length=64)
    status: str = Field(default="online", max_length=32)
    measurement_scope: str | None = Field(default=None, max_length=32)
    measurement_quality: str | None = Field(default=None, max_length=32)
    capabilities: dict = Field(default_factory=dict)
    # Last sequence the agent has generated locally (for stale detection).
    last_sequence: int | None = Field(default=None, ge=0)


class HeartbeatOut(BaseModel):
    server_time: datetime
    next_heartbeat_seconds: int
    config_version: int
    acknowledged_sequence: int | None = None
    status: str = "ok"


class UsageInterfaceIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1, max_length=120)
    bytes_received_total: int = Field(ge=0)
    bytes_sent_total: int = Field(ge=0)
    # Agent-detected reset since its previous observation for this interface.
    reset: bool = False


class UsageReportIn(BaseModel):
    model_config = ConfigDict(extra="forbid")

    schema_version: int = Field(default=SCHEMA_VERSION)
    sequence: int = Field(ge=0)
    observed_at: datetime
    measurement_scope: str = Field(default=MeasurementScope.UNKNOWN, max_length=32)
    measurement_quality: str = Field(default=MeasurementQuality.UNKNOWN, max_length=32)
    interfaces: list[UsageInterfaceIn] = Field(default_factory=list, max_length=128)
    note: str | None = Field(default=None, max_length=500)

    @field_validator("measurement_scope")
    @classmethod
    def _scope(cls, v: str) -> str:
        if v not in MeasurementScope.ALL:
            raise ValueError(f"unsupported measurement_scope: {v}")
        return v

    @field_validator("measurement_quality")
    @classmethod
    def _quality(cls, v: str) -> str:
        if v not in MeasurementQuality.ALL:
            raise ValueError(f"unsupported measurement_quality: {v}")
        return v

    @model_validator(mode="after")
    def _unique_interfaces(self) -> "UsageReportIn":
        names = [i.name for i in self.interfaces]
        if len(names) != len(set(names)):
            raise ValueError("interface names must be unique within a report")
        return self


class AcceptedInterface(BaseModel):
    name: str
    received_bytes: int
    sent_bytes: int
    accepted: bool
    reason: str | None = None
    from_reset: bool = False


class UsageReportOut(BaseModel):
    schema_version: int = SCHEMA_VERSION
    accepted: bool
    duplicate: bool = False
    reason: str | None = None
    server_time: datetime
    acknowledged_sequence: int
    received_bytes: int = 0
    sent_bytes: int = 0
    interfaces: list[AcceptedInterface] = Field(default_factory=list)


class AgentConfigOut(BaseModel):
    schema_version: int = SCHEMA_VERSION
    config_version: int = 1
    heartbeat_interval_seconds: int
    reporting_interval_seconds: int
    stale_after_minutes: int
    interface_policy: str
    server_time: datetime
    notes: list[str] = Field(default_factory=list)